function [E,m,s,Cp] = expm_charlier(A,argin)
% Computes the matrix exponential of A using the scaling and squaring 
% algorithm and the Charlier polynomial approximation.
%
% Inputs:
% - A:     input matrix.
% - argin: input 3-vector:
%          - argin(1): minimum value of the approximation polynomial order. 
%                      Possible values are 2, 4, 6, 9, 12, 12, 16, 20, 25, 
%                      30, 36, 42, 49, 56, 64.
%          - argin(2): maximum value of the approximation polynomial order. 
%                      Possible values are 2, 4, 6, 9, 12, 12, 16, 20, 25, 
%                      30, 36, 42, 49, 56, 64.
%           - argin(3): parameter x value (1, 2, 3, 5).
%
% Outputs: 
% - E:    exponential of matrix A.
% - m:    approximation polynomial order used.
% - s:    scaling parameter.
% - Cp:   cost in terms of number of matrix products.  
%
% Authors: Javier Ibáñez, José M. Alonso. 
%
% Group of High Performance Scientific Computation (HiPerSC)
% Universitat Politecnica de Valencia (Spain)
% http://hipersc.blogs.upv.es

% Default values
if nargin<2
    mmin=25;
    mmax=49;
    x=1;
elseif length(argin)<1
    mmin=25;
    mmax=49;
    x=1;    
elseif length(argin)<2
    mmin=argin(1);
    mmax=49;
    x=1;    
elseif length(argin)<3
    mmin=argin(1);
    mmax=argin(2);
    x=1;    
else
    mmin=argin(1);
    mmax=argin(2);
    x=argin(3);
end

% Select m and s values
[m,s,pA,nProd_ms]=select_m_s(A,mmin,mmax);

% Scaling technique
pA=scaling(pA,s);

% Get Charlier polynomial coefficients
p=coefs_exp_charlier(m,x);

% Polynomial evaluation by means of Paterson-Stockmeyer algorithm
[fA,nProd_eval] = polyvalm_paterson_stockmeyer(p,pA);

% Squaring technique
[E,nProd_sq]=squaring(fA,s);

% Total number of matrix products
Cp=nProd_ms+nProd_eval+nProd_sq;
end

function [m,s,pA,nProd]=select_m_s(A,mmin,mmax)
% [m,s,pA,nProd]=select_m_s(A,mmin,mmax)
%
% Provides the m and s values for computing the matrix exponential of A
% by means of the code selecciona_ms_conEstNormaConvergeAlpha.
%
% Inputs:
% - A:    the input matrix
% - mmin: minimum value of the approximation polynomial order. Possible 
%         values are 2, 4, 6, 9, 12, 12, 16, 20, 25, 30, 36, 42, 49, 56, 
%         64.
% - mmax: maximum value of the approximation polynomial order. Possible 
%         values are 2, 4, 6, 9, 12, 12, 16, 20, 25, 30, 36, 42, 49, 56, 
%         64.
%
% Outputs: 
% - m:    approximation polynomial order used.
% - s:    scaling parameter.
% - pA:   cell array with the powers of A nedeed, such that pA(i) contains
%         A^i, for i=1,2,3,...,q.
% -nProd: Number of matrix products required by the function.  

M=[2 4 6 9 12 16 20 25 30 36 42 49 56 64];
theta=[8.7334702258487179e-06  % m= 2 
       1.6783942982781048e-03  % m= 4 
       1.7764527083684662e-02  % m= 6 
       1.1483174747739708e-01  % m= 9 
       3.3521368782861483e-01  % m=12 
       8.2460319163860885e-01  % m=16 
       1.5041473223951629	   % m=20 
       2.5585766884181380	   % m=25 
       3.7810696269831392	   % m=30 
       5.4064650937902918	   % m=36 
       7.1556200904384877	   % m=42 
       9.3073843996022152	   % m=49 
       11.5453483152121912	   % m=56 
       14.1791073371113185]';  % m=64 

pot_ceil=ceil(sqrt(M));
pot_floor=floor(sqrt(M));

if mmin<M(1)
    mmin=M(1);
elseif mmin>M(end)
    mmin=M(end);
end

if mmax<M(1)
    mmax=M(1);
elseif mmin>M(end)
    mmax=M(end);
end

if mmin>mmax
    error('mmax must be greater than or equal to mmin');
end 

i=1;
found=0;
while i<=length(M) && found==0
    if M(i)==mmin
        imin=i;
        found=1;
    else
        i=i+1;
    end
end
if found==0
    error('mmin not allowed (use 2, 4, 6, 9, 12, 16, 20, 25, 30, 36, 42, 49, 56, or 64)');
end

i=1;
found=0;
while i<=length(M) && found==0
    if M(i)==mmax
        imax=i;
        found=1;
    else
        i=i+1;
    end
end
if found==0
    error('mmax not allowed (use 2, 4, 6, 9, 12, 16, 20, 25, 30, 36, 42, 49, 56, or 64)');
end

pA{1}=A;
nProd=0;
for i=1:imin-1
    j=pot_ceil(i);
    if j>pot_floor(i)
        pA{j}=pA{j-1}*A;
        nProd=nProd+1;        
    end
end

alfa=zeros(1,imax);
i=imin;
alfa(i-1)=norm1pp(pA{j},pot_floor(i-1),A)^(1/(M(i-1)+1));
f=0;
while f==0 && i<=imax
    j=pot_ceil(i);
    if j>pot_floor(i)   
        pA{j}=pA{j-1}*A;
        nProd=nProd+1;       
    end   
    
    alfa(i)=norm1pp(pA{j},pot_floor(i),A)^(1/(M(i)+1));

    if alfa(i)<theta(i)
        f=1;
    elseif abs(alfa(i)-alfa(i-1))<0.1
        f=2;
    else 
        i=i+1;
    end
end

switch f
    case 0
        m=M(imax); 
        s=max(0,ceil(log2(alfa(imax)/theta(imax))));
        if s==Inf
            s=12;
        end
    case 1
        m=M(i); 
        s=0;
    case 2
        s(i)=max(0,ceil(log2(alfa(i)/theta(i))));
        coste(i)=i+s(i); 
        for k=i+1:imax
            s(k)=max(0,ceil(log2(alfa(i)/theta(k))));
            coste(k)=k+s(k);
        end
        [~,p]=min(coste(imax:-1:i));
        p=imax-p+1;
        s=s(p);
        m=M(p);
        for k=i+1:p
            j=pot_ceil(k);
            if j>pot_floor(k)   
                pA{j}=pA{j-1}*A;
                nProd=nProd+1; 
            end
        end        
end
end

function pA = scaling(pA,s)
% pA=scaling(pA,s)
%
% Scaling of A powers.
%
% Inputs:
% - pA: cell array with the powers of A nedeed. pA{i} contains A^i, 
%       for i=1,2,3,...,q.
% - s:  scaling parameter.
%
% Outputs:
% - pA: cell array with the powers of A after scaling.

if s>0
    q=length(pA);
    for k=1:q
        pA{k}=pA{k}/(2^(k*s));
    end
end
end

function [A,nProd] = squaring(A,s)
% [A,nProd]=squaring(A,s)
%
% Squaring of A.
%
% Inputs:
% - A:    matrix resulting of the approximation polynomial evaluation.
% - s:    scaling parameter.
%
% Outputs:
% - A:    the exponential of matrix A after squaring technique.
% -nProd: number of matrix products carried out by the function.  

for i=1:s
    A=A*A;
end
nProd=s;
end

